/**
 * `npm run creators`: fetches what the Criadores page shows of each video in
 * `CREATOR_VIDEOS` (src/data/creators.ts), so the build never goes online.
 * The title and thumbnail come from the platform's oEmbed; for YouTube, the
 * date and length from the watch page. Thumbnails land in `public/creators/`
 * (TikTok's links expire), the rest in `src/data/creatorVideos.generated.ts`.
 * Videos already there are kept as they are; `--all` fetches them again.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { CREATOR_VIDEOS, videoOf } from '../src/data/creators.ts'
import { VIDEO_META } from '../src/data/creatorVideos.generated.ts'

const OUT = new URL('../src/data/creatorVideos.generated.ts', import.meta.url)
const PUBLIC = new URL('../public/', import.meta.url)
const all = process.argv.includes('--all')

const OEMBED = {
  youtube: (url) => `https://www.youtube.com/oembed?format=json&url=${encodeURIComponent(url)}`,
  tiktok: (url) => `https://www.tiktok.com/oembed?url=${encodeURIComponent(url)}`,
}

const get = async (url) => {
  const res = await fetch(url, { headers: { 'user-agent': 'Mozilla/5.0 (pokemonsurvivors.com creators script)' } })
  if (!res.ok) throw new Error(`${res.status} ${url}`)
  return res
}

/** The watch page's schema.org meta (`datePublished`, `duration`), or null when YouTube leaves it out. */
const youtubeMeta = async (id) => {
  const page = await (await get(`https://www.youtube.com/watch?v=${id}`)).text()
  const prop = (name) => page.match(new RegExp(`itemprop="${name}" content="([^"]+)"`))?.[1] ?? null
  return { date: prop('datePublished'), duration: prop('duration') }
}

const meta = { ...VIDEO_META }
mkdirSync(new URL('creators/', PUBLIC), { recursive: true })

for (const { url } of CREATOR_VIDEOS) {
  const video = videoOf(url)
  if (!video) throw new Error(`Can't read this video URL: ${url}`)
  const thumb = `/creators/${video.platform}-${video.id}.jpg`
  if (!all && meta[video.id] && existsSync(new URL(thumb.slice(1), PUBLIC))) continue
  const oembed = await (await get(OEMBED[video.platform](url))).json()
  // YouTube's hqdefault is 4:3 with the 16:9 frame inside: the page crops the bars.
  const image = video.platform === 'youtube' ? `https://i.ytimg.com/vi/${video.id}/hqdefault.jpg` : oembed.thumbnail_url
  writeFileSync(new URL(thumb.slice(1), PUBLIC), Buffer.from(await (await get(image)).arrayBuffer()))
  const extra = video.platform === 'youtube' ? await youtubeMeta(video.id) : { date: null, duration: null }
  meta[video.id] = { title: oembed.title, ...extra, thumb }
  console.log(`${video.id}: ${oembed.title}`)
}

const rows = Object.entries(meta).map(([id, m]) => `  ${JSON.stringify(id)}: ${JSON.stringify(m)},`)
writeFileSync(
  OUT,
  `import type { VideoMeta } from './creators'

/** Generated by \`npm run creators\` (scripts/creators.mjs) from \`CREATOR_VIDEOS\`, by video id. Don't edit by hand. */
export const VIDEO_META: Readonly<Record<string, VideoMeta>> = {
${rows.join('\n')}
}
`,
)
