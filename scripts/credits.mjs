// Writes CREDITS.md: the SpriteCollab artists behind every sprite and portrait the game ships.
// SpriteCollab's CC BY-NC 4.0 asks for credit per artist, so rerun this after `npm run assets`.
// Usage: npm run credits
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { DEX, FORMS, LOCAL_FORMS, pad } from './dex.mjs'

const ROOT = new URL('..', import.meta.url).pathname
const MANIFEST = join(ROOT, 'src/data/sprites.generated.json')
const OUT = join(ROOT, 'CREDITS.md')
const COLLAB = 'https://raw.githubusercontent.com/PMDCollab/SpriteCollab/master'

const [tracker, names, manifest] = await Promise.all([
  fetch(`${COLLAB}/tracker.json`).then((r) => r.json()),
  fetch(`${COLLAB}/credit_names.txt`).then((r) => r.text()),
  readFile(MANIFEST, 'utf8').then(JSON.parse),
])

/** Discord id (or plain name) -> { name, contact }, from credit_names.txt (Name, Discord, Contact). */
const people = new Map(
  names
    .split('\n')
    .slice(1)
    .map((line) => line.split('\t'))
    .filter(([name, id]) => name && id)
    .map(([name, id, contact = '']) => [id.trim(), { name: name.trim(), contact: contact.trim() }]),
)

const person = (id) => {
  const known = people.get(id)
  if (!known) return id.startsWith('<@') ? 'Anonymous' : id
  return known.contact.startsWith('http') ? `[${known.name}](${known.contact})` : known.name
}

/** Primary and secondary artists of a tracker credit entry, deduplicated. */
const artists = (credit) =>
  [...new Set([credit.primary, ...credit.secondary].filter(Boolean).map(person))].join(', ') || '—'

const rows = DEX.flatMap((dex) => {
  const entry = tracker[pad(dex)]
  const shiny = manifest[dex]?.shiny && entry.subgroups['0000']?.subgroups['0001']
  const row = (label, node, portrait = true) =>
    `| ${dex} | ${label} | ${artists(node.sprite_credit)} | ${portrait ? artists(node.portrait_credit) : '—'} |`
  // Alternate forms ship sprites only (no portrait); their shiny sits under `<id>/0001`.
  // Forms drawn for the game (`LOCAL_FORMS`) aren't SpriteCollab's: they get the AI section below.
  const forms = Object.keys(manifest[dex]?.forms ?? {}).filter((key) => !LOCAL_FORMS[dex]?.[key]).flatMap((key) => {
    const node = entry.subgroups[FORMS[dex][key]]
    const formShiny = manifest[dex].forms[key].shiny && node.subgroups['0001']
    const name = node.name.replaceAll('_', ' ')
    return [row(`${entry.name} (${name})`, node, false), ...(formShiny ? [row(`${entry.name} (${name}, shiny)`, formShiny, false)] : [])]
  })
  return [row(entry.name, entry), ...(shiny ? [row(`${entry.name} (shiny)`, shiny)] : []), ...forms]
})

/** One line per form in `LOCAL_FORMS`, named like SpriteCollab's rows ("Venusaur (Mega)"), shiny included when shipped. */
const aiRows = Object.entries(LOCAL_FORMS).flatMap(([dex, forms]) =>
  Object.entries(forms).map(([key, { madeWith, anims }]) => {
    const name = `${tracker[pad(Number(dex))].name} (${key.replace(/^mega(.?)$/, (_, x) => (x ? `Mega ${x}` : 'Mega'))})`
    const shiny = manifest[dex]?.forms?.[key]?.shiny ? ', normal and shiny' : ''
    return `- #${dex} ${name}: ${Object.keys(anims).join(', ')} sheets${shiny}, made with ${madeWith}`
  }),
)

const md = `# Credits

Pokémon Survivors is a non-commercial fan project. Pokémon is © Nintendo, Creatures Inc. and GAME FREAK inc.

## Sprites and portraits

All Pokémon sprites and portraits (except the AI-generated sheets listed below) come from [PMD SpriteCollab](https://sprites.pmdcollab.org) and are
used under [CC BY-NC 4.0](https://creativecommons.org/licenses/by-nc/4.0/). Entries credited to
CHUNSOFT are original *Pokémon Mystery Dungeon* sprites. This file is generated by \`npm run credits\`.

| # | Pokémon | Sprite | Portrait |
| --: | --- | --- | --- |
${rows.join('\n')}

## AI-generated sprites

SpriteCollab has no sprite sheets yet for these forms, so their sheets were generated for this game with AI, then
put on the base form's PMD palette, outlined and anchored like the SpriteCollab sheets. They will be replaced by
SpriteCollab art as soon as it exists there.

${aiRows.join('\n')}

## Shop art

The Kecleon shop's buildings, props, its own icons (the daily gift, the expansion, the wishlist, the loyalty
stamp and the Kecleon Egg), Meowth's caravan and the seasonal stalls in the lobby
(\`public/assets/shop/\`) were generated for this project with [PixelLab](https://www.pixellab.ai). The emotion
portraits in the dialogue box (Kecleon, Meowth, Duskull and Delibird) are SpriteCollab portraits,
credited in their rows above.

## Cries

Cries come from [PokéAPI/cries](https://github.com/PokeAPI/cries).

## Item icons and scenery

Item icons (held items, Poké Mart upgrades, consumables, the Kecleon shop's Bag items, evolution items,
Bottle Caps and TMs) are the official item sprites from [PokéAPI/sprites](https://github.com/PokeAPI/sprites).
Loaded Dice, Fairy Feather, Black Augurite, Auspicious Armor and Malicious Armor only exist there as HD art,
so they were converted to pixel art with [PixelLab](https://www.pixellab.ai).
Towers, trees, rocks, bushes and other painted scenery were made for this game with [PixelLab](https://www.pixellab.ai).

## Fonts

[Press Start 2P](https://fonts.google.com/specimen/Press+Start+2P) by CodeMan38 and
[VT323](https://fonts.google.com/specimen/VT323) by Peter Hull, both under the SIL Open Font License,
via [Fontsource](https://fontsource.org).
`

await writeFile(OUT, md)
console.log(`Wrote ${OUT} (${rows.length} rows)`)
