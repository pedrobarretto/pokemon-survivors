// Refreshes the tier list's snapshot (src/data/tierRuns.ts) from PostHog: finished
// standard-mode runs of the last 30 days, per starter and difficulty, from `run_end`.
// The site never queries PostHog; it ranks from the committed snapshot (src/site/tierList.ts).
//
//   POSTHOG_PERSONAL_API_KEY=phx_… node scripts/tierlist.mjs   # query PostHog (a personal key with query read access)
//   node scripts/tierlist.mjs runs.csv                          # or rewrite from a CSV export of the same query
import { readFileSync, writeFileSync } from 'node:fs'

const PROJECT = 674834
const DAYS = 30
const OUT = new URL('../src/data/tierRuns.ts', import.meta.url)
const DIFFS = ['normal', 'hard', 'nightmare']

// Wins are victories (beat Mewtwo) and endless runs (beat Mewtwo and kept going). No mode = runs from before modes, standard.
const QUERY = `SELECT properties.starter AS starter, properties.difficulty AS diff, count() AS runs,
  countIf(properties.outcome IN ('victory','endless')) AS wins, round(avg(toFloat(properties.minute)),2) AS avg_minute
FROM events WHERE event = 'run_end' AND timestamp > now() - INTERVAL ${DAYS} DAY
  AND (properties.mode = 'standard' OR properties.mode IS NULL)
  AND (properties.challenge IS NULL OR properties.challenge = '' OR properties.challenge = 'false')
  AND properties.outcome IN ('gameover','victory','endless')
GROUP BY starter, diff`

/** Rows as `[starter, diff, runs, wins, avgMinute]`, from PostHog or a CSV export with the same columns. */
const fetchRows = async () => {
  const csv = process.argv[2]
  if (csv) return readFileSync(csv, 'utf8').trim().split('\n').slice(1).map((line) => line.split(','))
  const key = process.env.POSTHOG_PERSONAL_API_KEY
  if (!key) throw new Error('Set POSTHOG_PERSONAL_API_KEY (or pass a CSV export)')
  const res = await fetch(`https://us.posthog.com/api/projects/${PROJECT}/query/`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ query: { kind: 'HogQLQuery', query: QUERY } }),
  })
  if (!res.ok) throw new Error(`PostHog ${res.status}: ${await res.text()}`)
  return (await res.json()).results
}

const rows = (await fetchRows())
  .map(([starter, diff, runs, wins, minute]) => ({ starter: String(starter ?? ''), diff: String(diff ?? ''), runs: Number(runs), wins: Number(wins), minute: Number(minute) }))
  .filter((r) => /^[a-z]+$/.test(r.starter) && DIFFS.includes(r.diff) && r.runs > 0)

const families = [...new Set(rows.map((r) => r.starter))].sort()
const cell = (r) => `${r.diff}: { runs: ${r.runs}, wins: ${r.wins}, minute: ${r.minute} }`
const lines = families.map((f) => {
  const cells = DIFFS.flatMap((d) => rows.filter((r) => r.starter === f && r.diff === d)).map(cell)
  return `  ${f}: { ${cells.join(', ')} },`
})
const date = new Date().toISOString().slice(0, 10)

writeFileSync(
  OUT,
  `import type { Difficulty } from '../game/difficulty'
import type { HatchlingId } from './hatchlings'
import type { StarterId } from './starters'

// Generated by \`node scripts/tierlist.mjs\` from PostHog's \`run_end\`. Don't edit by hand.

/** When the snapshot was taken and the window it covers (the last \`days\` days up to \`date\`). */
export const TIER_SNAPSHOT = { date: '${date}', days: ${DAYS} } as const

/**
 * Finished standard-mode runs (no Desafio do dia) per starter and difficulty:
 * how many, how many beat Mewtwo (endless runs count) and the average minute
 * reached. The tier list (\`site/tierList.ts\`) ranks from this; a family
 * missing here has no runs yet.
 */
export const TIER_RUNS = {
${lines.join('\n')}
} as const satisfies Partial<Record<StarterId | HatchlingId, Partial<Record<Difficulty, { runs: number; wins: number; minute: number }>>>>
`,
)
console.log(`Wrote ${families.length} families, ${rows.reduce((n, r) => n + r.runs, 0)} runs (${date}) to src/data/tierRuns.ts`)
