/** A language's moves: each signature's description and its level-up lines. */
const movesOf = (w: Words, text: Record<GaKitAMoveId, string>) => {
  const lines = stepLines(w)
  const move = <K extends GaKitAMoveId>(id: K) => ({ description: text[id], upgrades: lines[id] })
  return {
    clangingScales: move('clangingScales'),
    dualChop: move('dualChop'),
    sing: move('sing'),
    beatUp: move('beatUp'),
    hornAttack: move('hornAttack'),
    shadowSneak: move('shadowSneak'),
    ominousWind: move('ominousWind'),
    poisonJab: move('poisonJab'),
    teatime: move('teatime'),
    falseSurrender: move('falseSurrender'),
    nuzzle: move('nuzzle'),
    steelWing: move('steelWing'),
    thunderPunch: move('thunderPunch'),
    flameBurst: move('flameBurst'),
    bugBite: move('bugBite'),
  } as const
}

